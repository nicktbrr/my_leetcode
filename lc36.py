from typing import List


class Solution:
    def isValidSudoku(self, board: List[List[str]]) -> bool:
        n = len(board)
        row_d = {}
        col_d = {}
        boxes = {}
        for row in range(n):
            for col in range(n):
                val = board[row][col]
                box = (row // 3, col // 3, val)
                if val == '.':
                    continue
                if (row, val) not in row_d and (col, val) not in col_d and box not in boxes:
                    boxes[box] = 1
                    row_d[(row, val)] = 1
                    col_d[(col, val)] = 1
                else:
                    return False
        return True


